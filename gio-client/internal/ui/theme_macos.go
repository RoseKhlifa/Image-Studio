package ui

func macOSDesktopThemeSpec(colorMode string) desktopThemeTokens {
	colorMode = normalizeDesktopColorMode(colorMode)
	colors := macOSDesktopColors(colorMode)
	return desktopThemeTokens{
		Style:            desktopStyleMacOS,
		ColorMode:        colorMode,
		SurfaceTreatment: desktopSurfaceLiquidGlass,
		Colors:           colors,
		Metrics: desktopThemeMetrics{
			HeaderHeight:       68,
			WorkspaceBarHeight: 40,
			CommandBarHeight:   50,
			StatusBarHeight:    28,
			ControlHeight:      34,
			InputHeight:        34,
			IconTargetSize:     32,
			RowHeight:          34,
			LeftPaneWidth:      408,
			RightPaneWidth:     352,
			ConsoleHeight:      220,
			NodeWidth:          248,
			ControlRadius:      17,
			CardRadius:         22,
			BadgeRadius:        17,
			ModalRadius:        22,
			InputRadius:        14,
			NodeRadius:         14,
		},
	}
}

