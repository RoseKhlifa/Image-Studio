package ui

func macOSDesktopThemeSpec(colorMode string) desktopThemeTokens {
	colorMode = normalizeDesktopColorMode(colorMode)
	colors := macOSDesktopColors(colorMode)
	return desktopThemeTokens{
		Style:            desktopStyleMacOS,
		ColorMode:        colorMode,
		SurfaceTreatment: desktopSurfaceSolid,
		Colors:           colors,
		Metrics: desktopThemeMetrics{
			HeaderHeight:       52,
			WorkspaceBarHeight: 36,
			CommandBarHeight:   42,
			StatusBarHeight:    26,
			ControlHeight:      30,
			InputHeight:        30,
			IconTargetSize:     30,
			RowHeight:          34,
			LeftPaneWidth:      312,
			RightPaneWidth:     320,
			ConsoleHeight:      220,
			NodeWidth:          248,
			ControlRadius:      7,
			CardRadius:         8,
			BadgeRadius:        9,
			ModalRadius:        12,
			InputRadius:        7,
			NodeRadius:         8,
		},
	}
}

