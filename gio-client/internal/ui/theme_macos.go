package ui

func macOSDesktopThemeSpec(colorMode string) desktopThemeTokens {
	colorMode = normalizeDesktopColorMode(colorMode)
	colors := macOSDesktopColors(colorMode)
	return desktopThemeTokens{
		Style:            desktopStyleMacOS,
		ColorMode:        colorMode,
		SurfaceTreatment: desktopSurfaceSolid,
		Colors:           colors,
		Metrics: desktopThemeMetrics{
			HeaderHeight:       44,
			WorkspaceBarHeight: 40,
			CommandBarHeight:   40,
			StatusBarHeight:    28,
			ControlHeight:      28,
			InputHeight:        28,
			IconTargetSize:     32,
			RowHeight:          32,
			LeftPaneWidth:      244,
			RightPaneWidth:     304,
			ConsoleHeight:      220,
			NodeWidth:          248,
			ControlRadius:      6,
			CardRadius:         8,
			BadgeRadius:        6,
			ModalRadius:        10,
			InputRadius:        6,
			NodeRadius:         8,
		},
	}
}

