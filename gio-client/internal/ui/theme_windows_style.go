package ui

func windowsDesktopThemeSpec(colorMode string) desktopThemeTokens {
	colorMode = normalizeDesktopColorMode(colorMode)
	return desktopThemeTokens{
		Style:            desktopStyleWindows,
		ColorMode:        colorMode,
		SurfaceTreatment: desktopSurfaceSolid,
		Colors:           windowsDesktopColors(colorMode),
		Metrics: desktopThemeMetrics{
			HeaderHeight:       48,
			WorkspaceBarHeight: 38,
			CommandBarHeight:   48,
			StatusBarHeight:    36,
			ControlHeight:      32,
			InputHeight:        32,
			IconTargetSize:     32,
			RowHeight:          32,
			LeftPaneWidth:      360,
			RightPaneWidth:     320,
			ConsoleHeight:      220,
			NodeWidth:          248,
			ControlRadius:      4,
			CardRadius:         8,
			BadgeRadius:        4,
			ModalRadius:        8,
			InputRadius:        4,
			NodeRadius:         8,
		},
	}
}

